"""Shared utilities for the spine project: data loading, character vocabulary, splits.

The default corpus is `data/tales.txt` (generated by `data/make_tales.py`): one short story per
line, the last 10% of lines held out.  Every stage uses the same corpus and the same split, so
numbers are comparable from Stage 01 to Stage 12.  Pass --data to use another text file.
"""
import json
import pathlib

import numpy as np

DATA_DIR = pathlib.Path(__file__).parent / "data"
DEFAULT_DATA = DATA_DIR / "tales.txt"


def load_lines(path=DEFAULT_DATA):
    return pathlib.Path(path).read_text(encoding="utf-8").rstrip("\n").split("\n")


def load_manifest():
    return json.loads((DATA_DIR / "tales_manifest.json").read_text())


def split_lines(lines, val_fraction=0.1):
    n_val = max(1, int(round(len(lines) * val_fraction)))
    return lines[:-n_val], lines[-n_val:]


def encode(text, vocab):
    stoi = {c: i for i, c in enumerate(vocab)}
    return np.array([stoi[c] for c in text], dtype=np.int64)


def decode(ids, vocab):
    return "".join(vocab[int(i)] for i in ids)


def load_corpus(path=DEFAULT_DATA, val_fraction=0.1, train_lines=None):
    """Return (train_ids, val_ids, vocab). Split by line (story): the last val_fraction of lines is
    held out, so no story is cut in half.  `train_lines` may replace the training lines (e.g. after
    deduplication in Stage 07) while keeping the vocabulary and the held-out split fixed."""
    lines = load_lines(path)
    train, val = split_lines(lines, val_fraction)
    if train_lines is not None:
        train = train_lines
    vocab = sorted(set("\n".join(lines) + "\n"))
    return encode("\n".join(train) + "\n", vocab), encode("\n".join(val) + "\n", vocab), vocab


def nll(prob_table, ids):
    """Mean negative log-likelihood (nats/token) of a bigram table P[a, b] = p(b | a) on a sequence."""
    p = prob_table[ids[:-1], ids[1:]]
    return float(-np.mean(np.log(p)))


CKPT_DIR = pathlib.Path(__file__).parent / "checkpoints"


def save_checkpoint(name, params, cfg, **meta):
    """Save float32 parameters + config + metadata to checkpoints/<name>.npz."""
    from dataclasses import asdict

    CKPT_DIR.mkdir(exist_ok=True)
    arrays = {f"p/{k}": v.astype(np.float32) for k, v in params.items()}
    np.savez_compressed(CKPT_DIR / f"{name}.npz", **arrays, _cfg=json.dumps(asdict(cfg)), _meta=json.dumps(meta))


def load_checkpoint(name):
    """Return (params as float64, Config, meta) or None if the checkpoint does not exist."""
    import model

    path = CKPT_DIR / f"{name}.npz"
    if not path.exists():
        return None
    z = np.load(path)
    params = {k[2:]: z[k].astype(np.float64) for k in z.files if k.startswith("p/")}
    return params, model.Config(**json.loads(str(z["_cfg"]))), json.loads(str(z["_meta"]))
